create table store (
    id              bigint              generated by default as identity primary key,
    mgmt_no         varchar(40)         not null unique,
    cell_id         bigint              not null references cell (cell_id),
    name            varchar(100)        not null,
    name_romanized  varchar(200),
    category        varchar(10)         not null,
    sub_type        varchar(50),
    franchise       boolean             not null,
    road_addr       varchar(200)        not null,
    road_addr_en    varchar(300),
    lat             double precision    not null,
    lng             double precision    not null,
    license_date    date                not null,
    google_place_id varchar(100),
    verified_at     date                not null,
    active          boolean             not null
);

-- 칸의 매장 목록 API 가 칸 + 분류로 찾는다
create index idx_store_cell_category on store (cell_id, category);

-- Supabase 는 public 스키마 테이블을 공개 API 로 노출한다. 정책 없이 켜 두면 공개 API 로는 접근할 수 없다
alter table store enable row level security;
