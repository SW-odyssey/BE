create table cell_slot_score
(
	id            bigint generated by default as identity primary key,
	cell_id       bigint      not null references cell (cell_id),
	day_type      varchar(20) not null,
	time_slot     varchar(20) not null,
	density_level varchar(20),
	score         double precision,
	rank          integer,
	eligible      boolean     not null,
	version       varchar(50) not null,
	computed_at   timestamp   not null,
	unique (cell_id, day_type, time_slot)
);

create index idx_cell_slot_score_rank on cell_slot_score (day_type, time_slot, rank);

alter table cell_slot_score enable row level security;
